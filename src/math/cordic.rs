const STEPS: u8 = Base::FRAC_NBITS as u8;
const MAX_K: i64 = Base::INT_NBITS as i64 - 1;
const ATANH_DIRECT_MAX: Real = r!(0.8069);

fn circular_rotate(mut x: Real, mut y: Real, mut z: Real) -> (Real, Real) {
    for i in 0..STEPS {
        let xs = x >> i;
        let ys = y >> i;

        if z >= Real::ZERO {
            (x, y) = (x - ys, y + xs);
            z -= ATAN[i as usize];
        } else {
            (x, y) = (x + ys, y - xs);
            z += ATAN[i as usize];
        }
    }

    (x, y)
}

fn circular_vectorize(mut x: Real, mut y: Real, mut z: Real) -> (Real, Real) {
    for i in 0..STEPS {
        let xs = x >> i;
        let ys = y >> i;

        if y >= Real::ZERO {
            (x, y) = (x + ys, y - xs);
            z += ATAN[i as usize];
        } else {
            (x, y) = (x - ys, y + xs);
            z -= ATAN[i as usize];
        }
    }

    (x, z)
}

fn hyperbolic_rotate(mut x: Real, mut y: Real, mut z: Real) -> (Real, Real) {
    for i in HYPERBOLIC_ITERS {
        let xs = x >> i;
        let ys = y >> i;

        if z >= Real::ZERO {
            (x, y) = (x + ys, y + xs);
            z -= ATANH[i as usize];
        } else {
            (x, y) = (x - ys, y - xs);
            z += ATANH[i as usize];
        }
    }

    (x, y)
}

fn hyperbolic_vectorize(mut x: Real, mut y: Real, mut z: Real) -> (Real, Real) {
    for i in HYPERBOLIC_ITERS {
        let xs = x >> i;
        let ys = y >> i;

        if y >= Real::ZERO {
            (x, y) = (x - ys, y - xs);
            z += ATANH[i as usize];
        } else {
            (x, y) = (x + ys, y + xs);
            z -= ATANH[i as usize];
        }
    }

    (x, z)
}

fn normalize_angle(θ: Real) -> (Real, Real) {
    let k: i64 = (θ / Real::PI).round().into();

    let reduced = θ - Real::from(k) * Real::PI;
    let cos_sign = if k % 2 == 0 { Real::ONE } else { -Real::ONE };

    (reduced, cos_sign)
}

fn reduce_ln2(x: Real) -> (Real, i64) {
    let k: i64 = (x / Real::ln_2()).round().into();
    (x - Real::from(k as i64) * Real::ln_2(), k)
}

pub fn sin_cos(θ: Real) -> (Real, Real) {
    let (reduced, sign) = normalize_angle(θ);
    let (cos, sin) = circular_rotate(K_C, Real::zero(), reduced);

    (sin * sign, cos * sign)
}

pub fn asin(x: Real) -> Real {
    assert!(x >= -r!(1) && x <= r!(1), "asin argument outside of [-1, 1]");

    let c = sqrt((r!(1) - x) * (r!(1) + x));
    circular_vectorize(c, x, r!(0)).1
}

pub fn acos(x: Real) -> Real {
    Real::frac_pi_2() - asin(x)
}

pub fn atan(x: Real) -> Real {
    let neg = x.is_negative();
    let a = if neg { -x } else { x };

    let r = if a <= r!(1) {
        circular_vectorize(r!(1), a, Real::ZERO).1
    } else {
        (Real::frac_pi_2()) - circular_vectorize(r!(1), r!(1) / a, Real::ZERO).1
    };

    if neg { -r } else { r }
}

fn cosh_sinh_core(r: Real) -> (Real, Real) {
    hyperbolic_rotate(K_H, r!(0), r)
}

pub fn sinh_cosh(x: Real) -> (Real, Real) {
    let neg = x.is_negative();
    let a = if neg { -x } else { x };

    let (sinh, cosh) = if a <= Real::ONE {
        let (c, s) = cosh_sinh_core(a);
        (s, c)
    } else {
        let (r, k) = reduce_ln2(a); // here k >= 1
        if k > MAX_K {
            let m = Real::max_value().unwrap();
            (m, m)
        } else {
            let (c, s) = cosh_sinh_core(r);
            let ep = (c + s) << (k - 1) as u8;
            let en = (c - s) >> (k + 1) as u8;
            (ep - en, ep + en)
        }
    };

    (if neg { -sinh } else { sinh }, cosh)
}

pub fn asinh(x: Real) -> Real {
    let neg = x.is_negative();
    let a = if neg { -x } else { x };

    let r = if a < r!(2) {
        ln(a + sqrt(a * a + 1))
    } else {
        let inv = a.recip();
        ln(a) + ln(1 + sqrt(1 + inv * inv))
    };

    if neg { -r } else { r }
}

pub fn acosh(x: Real) -> Real {
    assert!(x >= r!(1), "acosh argument must be >= 1");

    if x < r!(2) {
        ln(x + sqrt((x - 1) * (x + 1)))
    } else {
        let inv = x.recip();
        ln(x) + ln(1 + sqrt(1 - inv * inv))
    }
}

pub fn atanh(x: Real) -> Real {
    assert!(x > -r!(1) && x < r!(1), "atanh argument outside (-1, 1)");

    if x >= -ATANH_DIRECT_MAX && x <= ATANH_DIRECT_MAX {
        hyperbolic_vectorize(r!(1), x, r!(0)).1
    } else {
        (ln(1 + x) - ln(1 - x)) >> 1
    }
}

pub fn exp(x: Real) -> Real {
    if x >= -r!(1) && x <= r!(1) {
        let (c, s) = cosh_sinh_core(x);
        return c + s;
    }

    let (r, k) = reduce_ln2(x);
    if k >= MAX_K {
        return Real::max_value().unwrap();
    }

    let (c, s) = cosh_sinh_core(r);

    if k < 0 {
        if -k > Base::FRAC_NBITS as i64 {
            return r!(0);
        }
        (c + s) >> -k as u8
    } else {
        (c + s) << k as u8
    }
}

pub fn ln(x: Real) -> Real {
    assert!(x > Real::ZERO, "ln argument must be > 0");

    // x = m · 2^e with m ∈ [0.75, 1.5)
    let mut m = x;
    let mut e = 0i64;

    while m >= r!(1.5) {
        m >>= 1;
        e += 1;
    }
    while m < r!(0.75) {
        m <<= 1;
        e -= 1;
    }

    // atanh((m-1)/(m+1)) = ½·ln m, computed without a division
    let z = hyperbolic_vectorize(m + 1, m - 1, r!(0)).1;

    z + z + Real::from(e) * Real::ln_2()
}

